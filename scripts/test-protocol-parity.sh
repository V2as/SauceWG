#!/usr/bin/env bash
# Checks that the three places which define an AmneziaWG generation still agree.
#
#   ./scripts/test-protocol-parity.sh
#
# The node container decides which parameters an interface carries (docker/awg/lib.sh),
# the panel renders the client profile that has to match it (backend/app/awg/protocol.py),
# and the installer writes the .env both read (saucewg.sh). A disagreement between any
# two of them is a tunnel that comes up and never handshakes, or a config a router
# silently refuses — neither of which shows up as an error anywhere.
#
# Needs bash 4+, python3 and jq.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)

PASSED=0
FAILED=0

GENERATIONS="1.0 1.5 2.0 3.0 3.1"
ALIASES="legacy 1 1.0 1.5 2 2.0 3 3.0 3.1"

check() {
    local what=$1 want=$2 got=$3
    if [ "$want" = "$got" ]; then
        printf '  ok   %s\n' "$what"
        PASSED=$((PASSED + 1))
    else
        printf '  FAIL %s\n         want: %s\n         got:  %s\n' "$what" "$want" "$got"
        FAILED=$((FAILED + 1))
    fi
}

# What both shell copies describe the same way: the generations, their spellings,
# which parameters both ends must share and what each is called in a .conf.
shell_report() {
    local suffixes=$1 shared=$2 v
    printf 'suffixes\t%s\n' "$suffixes"
    printf 'shared\t%s\n' "$shared"
    printf 'presets\t%s\n' "$AWG_CPS_PRESETS"
    printf 'min_padding\t%s\n' "$AWG_HEADER_PROTECTION_MIN_PADDING"
    printf 'default.clients\t%s\n' "$AWG_PROTOCOL_CLIENTS"
    printf 'default.nodes\t%s\n' "$AWG_PROTOCOL_NODES"
    for v in $GENERATIONS; do
        printf 'params.%s\t%s\n' "$v" "$(awg_protocol_params "$v")"
    done
    for v in $ALIASES; do
        printf 'alias.%s\t%s\n' "$v" "$(awg_protocol "$v")"
    done
    for v in $suffixes; do
        printf 'label.%s\t%s\n' "$v" "$(awg_param_label "$v")"
    done
    for v in $AWG_CPS_PRESETS; do
        printf 'preset.%s\t%s\n' "$v" "$(awg_cps_preset "$v")"
    done
}

# --- the node container ----------------------------------------------------
lib_report() {
    (
        # lib.sh calls die() on bad input; the harness only feeds it good input.
        # shellcheck source=../docker/awg/lib.sh
        . "$ROOT/docker/awg/lib.sh"
        shell_report "$AWG_OBF_SUFFIXES" "$AWG_SHARED_SUFFIXES"
    )
}

# --- the installer --------------------------------------------------------
cli_report() {
    (
        # Everything but the final `main "$@"`, so the helpers can be called directly.
        # shellcheck disable=SC1090
        . <(sed '/^main "\$@"$/d' "$ROOT/saucewg.sh")
        shell_report "$AWG_OBF_PARAMS" "$AWG_SHARED_PARAMS"
    )
}

# The 3.x timings are generated by the two shell copies only: the panel never
# invents a profile, it reads one back from the node.
timing_report() {
    local timing
    for timing in $AWG_TIMINGS; do
        printf 'timing.%s\t%s\n' "$timing" "$(awg_timing_default "$timing")"
    done
}

# --- the panel ------------------------------------------------------------
# Loaded from its file rather than as app.awg.protocol: the package __init__ opens a
# UAPI client and pulls in pydantic, and the generation table needs neither.
load_panel_module='
import importlib.util, os
path = os.path.join(os.environ["ROOT"], "backend", "app", "awg", "protocol.py")
spec = importlib.util.spec_from_file_location("awg_protocol", path)
p = importlib.util.module_from_spec(spec)
spec.loader.exec_module(p)
'

panel_report() {
    ROOT="$ROOT" GENERATIONS="$GENERATIONS" ALIASES="$ALIASES" python3 - <<PY
${load_panel_module}
print("suffixes\t" + " ".join(p.ALL_PARAMS))
print("shared\t" + " ".join(p.SHARED_PARAMS))
print("presets\t" + " ".join(p.CPS_PRESETS))
print(f"min_padding\t{p.HEADER_PROTECTION_MIN_PADDING}")
# Clients get the newest generation a stable KeeneticOS loads; nodes get the newest.
print(f"default.clients\t{p.LATEST_KEENETIC_PROTOCOL}")
print(f"default.nodes\t{p.LATEST_PROTOCOL}")
for v in os.environ["GENERATIONS"].split():
    print(f"params.{v}\t" + " ".join(p.PROTOCOL_PARAMS[v]))
for v in os.environ["ALIASES"].split():
    print(f"alias.{v}\t" + p.normalize(v))
for v in p.ALL_PARAMS:
    print(f"label.{v}\t" + p.label(v))
for name, spec in p.CPS_PRESETS.items():
    print(f"preset.{name}\t{spec}")
PY
}

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

lib_report   | sort > "$work/lib"
cli_report   | sort > "$work/cli"
panel_report | sort > "$work/panel"

echo "1. the node container and the installer describe the same generations"
check "every line matches" "" "$(diff "$work/lib" "$work/cli" || true)"
# shellcheck disable=SC1090
check "the same 3.x timings" \
    "$(. "$ROOT/docker/awg/lib.sh"; timing_report)" \
    "$(. <(sed '/^main "\$@"$/d' "$ROOT/saucewg.sh"); timing_report)"

echo "2. the panel agrees with the node container"
check "every line matches" "" "$(diff "$work/lib" "$work/panel" || true)"

echo "3. a generation is identified by the parameters it carries"
# If two generations listed the same parameters, nothing could tell them apart on the
# wire, and choosing between them would be a no-op.
check "each set is distinct" "5" "$(grep '^params\.' "$work/lib" | cut -f2 | sort -u | wc -l | tr -d ' ')"
# Each generation is the one before it plus something: a 3.1 node can be asked for
# anything a 3.0 node can, and so on down.
nested=yes
previous=""
for v in $GENERATIONS; do
    current=$(grep "^params\.${v}	" "$work/lib" | cut -f2)
    for param in $previous; do
        case " $current " in *" $param "*) ;; *) nested="no: ${v} drops ${param}" ;; esac
    done
    previous=$current
done
check "each generation extends the one before" "yes" "$nested"

echo "4. a generation nobody speaks is refused everywhere"
check "4.0 is refused by the node container" "refused" \
    "$(. "$ROOT/docker/awg/lib.sh"; awg_protocol 4.0 >/dev/null 2>&1 && echo accepted || echo refused)"
# shellcheck disable=SC1090
check "4.0 is refused by the installer" "refused" \
    "$(. <(sed '/^main "\$@"$/d' "$ROOT/saucewg.sh"); awg_protocol 4.0 >/dev/null 2>&1 && echo accepted || echo refused)"
check "4.0 is refused by the panel" "refused" \
    "$(ROOT="$ROOT" python3 -c "
${load_panel_module}
try:
    p.normalize('4.0')
    print('accepted')
except p.UnknownProtocol:
    print('refused')")"

echo "5. the panel tells a node's generation from the state it persisted"
check "a header protection key is 3.0" "3.0" \
    "$(ROOT="$ROOT" python3 -c "
${load_panel_module}
print(p.infer({'SERVER_S3': 20, 'SERVER_S4': 20, 'SERVER_HEADER_PROTECTION_KEY': 'k'}, prefix='SERVER_'))")"
check "RandomTrailers is 3.1" "3.1" \
    "$(ROOT="$ROOT" python3 -c "
${load_panel_module}
print(p.infer({'SERVER_HEADER_PROTECTION_KEY': 'k', 'SERVER_RANDOM_TRAILERS': 'on'}, prefix='SERVER_'))")"
check "S3 and S4 alone are 2.0" "2.0" \
    "$(ROOT="$ROOT" python3 -c "
${load_panel_module}
print(p.infer({'SERVER_S3': 20, 'SERVER_S4': 20}, prefix='SERVER_'))")"

echo
printf '%s passed, %s failed\n' "$PASSED" "$FAILED"
[ "$FAILED" -eq 0 ]
